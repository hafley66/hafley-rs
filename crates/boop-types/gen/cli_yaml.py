#!/usr/bin/env python3
"""Reverse-describe boop's clap tree into cli.yaml by reading clap's own help.

Source of truth is the installed binary, never main.rs: clap renders defaults,
value names and hidden-ness that the derive attributes only imply.
"""
import re
import subprocess
import sys
from pathlib import Path

BIN = sys.argv[1] if len(sys.argv) > 1 else "boop"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).parent.parent / "cli.yaml"
ENV = {"BOOP_NO_SYNC": "1", "RUST_LOG": "off", "PATH": "/usr/bin:/bin:/usr/local/bin:" + str(Path.home() / ".cargo/bin")}


def help_for(path):
    r = subprocess.run([BIN, *path, "--help"], capture_output=True, text=True, env=ENV)
    return r.stdout or r.stderr


AFTER_HELP = re.compile(r"^DOCTRINE\b")


def sections(text):
    """Split clap help into its labelled blocks, joining wrapped continuations."""
    out, cur = {}, None
    for raw in text.splitlines():
        if AFTER_HELP.match(raw):
            break
        m = re.match(r"^([A-Z][A-Za-z ]*):\s*$", raw)
        if m:
            cur = m.group(1).lower()
            out[cur] = []
            continue
        if raw.startswith("Usage:"):
            out["usage"] = [raw[len("Usage:"):].strip()]
            cur = None
            continue
        if cur is None:
            out.setdefault("_pre", []).append(raw)
        else:
            out[cur].append(raw)
    return out


ENTRY = re.compile(r"^\s{2,6}(\S.*?)(?:\s{2,}(.*))?$")


def entries(lines):
    """One (head, help) per entry; lines indented past the head continue it."""
    rows = []
    for raw in lines:
        if not raw.strip():
            continue
        m = ENTRY.match(raw)
        if m and not raw.startswith(" " * 10):
            rows.append([m.group(1).strip(), (m.group(2) or "").strip()])
        elif rows:
            rows[-1][1] = (rows[-1][1] + " " + raw.strip()).strip()
    return rows


def parse_option(head):
    short = long = value = None
    for piece in head.split(","):
        piece = piece.strip()
        vm = re.match(r"^(-{1,2}[A-Za-z0-9][\w-]*)(?:[ =]<([^>]+)>)?$", piece)
        if not vm:
            continue
        flag, val = vm.group(1), vm.group(2)
        if val:
            value = val
        if flag.startswith("--"):
            long = flag
        else:
            short = flag
    return short, long, value


def q(s):
    if s is None:
        return "null"
    s = str(s).replace("\\", "\\\\").replace('"', '\\"')
    return '"' + s + '"'


def walk(path, acc):
    text = help_for(path)
    sec = sections(text)
    about = " ".join(x.strip() for x in sec.get("_pre", []) if x.strip())
    node = {
        "path": " ".join(path) or "(root)",
        "argv": list(path),
        "about": about,
        "usage": (sec.get("usage") or [""])[0],
        "subcommands": [],
        "arguments": [],
        "options": [],
    }
    for head, helptext in entries(sec.get("commands", [])):
        name = head.split()[0]
        if name == "help":
            continue
        node["subcommands"].append({"name": name, "about": helptext})
    for head, helptext in entries(sec.get("arguments", [])):
        name = head.strip("[]<>.")
        node["arguments"].append(
            {"name": name, "required": head.startswith("<"), "variadic": "..." in head, "help": helptext}
        )
    for head, helptext in entries(sec.get("options", [])):
        short, long, value = parse_option(head)
        if long in ("--help", "--version"):
            continue
        node["options"].append({"short": short, "long": long, "value": value, "help": helptext})
    acc.append(node)
    for sub in node["subcommands"]:
        walk(path + [sub["name"]], acc)


acc = []
walk([], acc)


def op_id(argv):
    return "_".join(argv) if argv else "root"


ver = subprocess.run([BIN, "--version"], capture_output=True, text=True, env=ENV).stdout.strip()
L = [
    "# generated by crates/boop-types/gen/cli_yaml.py from the installed binary",
    "# every clap command path is a URL; every flag is a query parameter",
    "openapi: 3.1.0",
    "info:",
    "  title: boop cli",
    f"  version: {q(ver or 'unknown')}",
    f"  description: {q('Reverse description of the clap tree. A path segment is a subcommand.')}",
    "  license:",
    '    name: "MIT OR Apache-2.0"',
    '    identifier: "MIT OR Apache-2.0"',
    f"x-command-count: {len(acc)}",
    "servers:",
    "  - url: boop",
    f"    description: {q('The installed binary; a path segment is a subcommand.')}",
    "paths:",
]

for n in acc:
    required_pos = [a for a in n["arguments"] if a["required"]]
    url = "/" + "/".join(n["argv"]) + "".join("/{" + a["name"] + "}" for a in required_pos)
    L.append(f"  {q(url)}:")
    L.append("    post:")
    L.append(f"      operationId: {op_id(n['argv'])}")
    L.append(f"      summary: {q(n['about'] or ' '.join(n['argv']) or 'boop')}")
    L.append(f"      x-usage: {q(n['usage'])}")
    if n["subcommands"]:
        L.append("      x-subcommands:")
        for sc in n["subcommands"]:
            L.append(f"        - name: {q(sc['name'])}")
            L.append(f"          url: {q('/' + '/'.join(n['argv'] + [sc['name']]))}")
            L.append(f"          summary: {q(sc['about'])}")
    else:
        L.append("      x-subcommands: []")
    params = []
    for a in n["arguments"]:
        params.append(
            {"name": a["name"], "in": "path" if a["required"] else "query",
             "required": a["required"], "description": a["help"],
             "schema": "array" if a["variadic"] else "string", "x-clap": "positional"}
        )
    for o in n["options"]:
        params.append(
            {"name": o["long"] or o["short"], "in": "query", "required": False, "description": o["help"],
             "schema": "string" if o["value"] else "boolean",
             "x-clap": "flag" if not o["value"] else "option",
             "x-short": o["short"], "x-value-name": o["value"]}
        )
    if not params:
        L.append("      parameters: []")
    else:
        L.append("      parameters:")
        for prm in params:
            L.append(f"        - name: {q(prm['name'])}")
            L.append(f"          in: {prm['in']}")
            L.append(f"          required: {'true' if prm['required'] else 'false'}")
            L.append(f"          description: {q(prm['description'])}")
            if prm["schema"] == "array":
                L.append("          schema: { type: array, items: { type: string } }")
            else:
                L.append(f"          schema: {{ type: {prm['schema']} }}")
            L.append(f"          x-clap: {prm['x-clap']}")
            if prm.get("x-short"):
                L.append(f"          x-short: {q(prm['x-short'])}")
            if prm.get("x-value-name"):
                L.append(f"          x-value-name: {q(prm['x-value-name'])}")
    L.append("      responses:")
    L.append("        \"200\": { description: success, x-exit-code: 0 }")
    L.append("        \"400\": { description: clap parse error, x-exit-code: 2 }")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(L) + "\n")
opts = sum(len(n["options"]) for n in acc)
args = sum(len(n["arguments"]) for n in acc)
print(f"{len(acc)} paths, {args} positionals, {opts} options -> {OUT}")
