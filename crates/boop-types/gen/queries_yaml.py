#!/usr/bin/env python3
"""Emit queries.yaml: one OpenAPI operation per SQL statement in the crates.

Output columns come from sqlite preparing the statement, not from parsing it:
`SELECT *` and expression aliases have no column list in the text.
"""
import hashlib
import re
import sqlite3
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
DB = sys.argv[2] if len(sys.argv) > 2 else str(Path.home() / ".agent/boop.db")
OUT = Path(__file__).parent.parent / "queries.yaml"
CRATES = ["boop", "boop-acp", "boop-harness", "boop-mux", "boop-proc", "boop-store", "boop-turnstrip", "boop-turnvis"]

RAW = re.compile(r'r(#*)"(.*?)"\1', re.S)
PLAIN = re.compile(r'"((?:[^"\\]|\\.)*?)"', re.S)
VERB = re.compile(r"^\s*(SELECT|WITH|INSERT|UPDATE|DELETE|CREATE|DROP|PRAGMA|REPLACE|ALTER)\b", re.I)
READS = re.compile(r"\b(?:FROM|JOIN)\s+([a-z_][a-z0-9_]*)", re.I)
WRITES = re.compile(r"\b(?:INSERT(?:\s+OR\s+\w+)?\s+INTO|UPDATE|DELETE\s+FROM)\s+([a-z_][a-z0-9_]*)", re.I)
NAMED = re.compile(r"[:@$]([a-z_][a-z0-9_]*)", re.I)
WHERE_COL = re.compile(r"([a-z_][a-z0-9_.]*)\s*(?:=|<|>|<=|>=|<>|!=|\bLIKE\b|\bIN\b)\s*[?:@$]", re.I)

con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
tables = {r[0] for r in con.execute("SELECT name FROM sqlite_master WHERE type='table'")}
DECL = {}
for t in tables:
    for c in con.execute(f'PRAGMA table_info("{t}")'):
        DECL[(t, c[1])] = (c[2] or "TEXT").upper().split("(")[0]

TYPES = {"INTEGER": "integer", "TEXT": "string", "REAL": "number", "BLOB": "string"}


def statements():
    for crate in CRATES:
        for f in sorted((ROOT / "crates" / crate / "src").rglob("*.rs")):
            src = f.read_text(errors="replace")
            for m in list(RAW.finditer(src)) + list(PLAIN.finditer(src)):
                lit = m.group(2) if m.re is RAW else m.group(1)
                text = lit.strip()
                v = VERB.match(text)
                if not v or "{" in text:
                    continue
                yield str(f.relative_to(ROOT)), src[: m.start()].count("\n") + 1, v.group(1).upper(), text


def columns_of(sql):
    """Bind every parameter to NULL and take zero rows; the description is exact."""
    probe = re.sub(r"\?\d*|[:@$][a-z_][a-z0-9_]*", "NULL", sql, flags=re.I)
    if not re.search(r"\blimit\b", probe, re.I):
        probe = f"SELECT * FROM ({probe}) LIMIT 0"
    cur = con.execute(probe)
    raw = [d[0] for d in (cur.description or [])]
    cur.close()
    seen, cols = Counter(), []
    for c in raw:
        seen[c] += 1
        cols.append(c if seen[c] == 1 else f"{c}#{seen[c]}")
    return cols


def col_type(name, reads):
    for t in reads:
        if (t, name) in DECL:
            return TYPES.get(DECL[(t, name)], "string")
    if name.endswith("_id") or name.endswith("_ts") or name in ("turn", "seq"):
        return "integer"
    return "string"


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


ops, skipped, seen = [], Counter(), set()
for path, line, verb, sql in statements():
    key = hashlib.blake2s(re.sub(r"\s+", " ", sql).encode(), digest_size=4).hexdigest()
    if key in seen:
        continue
    seen.add(key)
    reads = sorted({t for t in READS.findall(sql) if t in tables})
    writes = sorted({t for t in WRITES.findall(sql) if t in tables})
    binds = len(re.findall(r"\?", sql)) or len(set(NAMED.findall(sql)))
    where_cols = [c.split(".")[-1] for c in WHERE_COL.findall(sql)]
    cols = []
    if verb in ("SELECT", "WITH"):
        try:
            cols = columns_of(sql)
        except sqlite3.Error as err:
            skipped[str(err).split(":")[0]] += 1
            continue
    primary = (writes or reads or ["_"])[0]
    ops.append(
        {"key": key, "url": f"/{primary}/{key}", "verb": verb, "sql": sql, "src": f"{path}:{line}",
         "reads": reads, "writes": writes, "binds": binds, "where": where_cols, "cols": cols}
    )

L = [
    "# generated by crates/boop-types/gen/queries_yaml.py",
    "# one operation per SQL statement; output columns come from sqlite, not a parser",
    "openapi: 3.1.0",
    "info:",
    "  title: boop store queries",
    f'  version: "{con.execute("PRAGMA user_version").fetchone()[0]}"',
    "  license:",
    '    name: "MIT OR Apache-2.0"',
    '    identifier: "MIT OR Apache-2.0"',
    "servers:",
    '  - url: "~/.agent/boop.db"',
    "    description: the sqlite store these statements were prepared against",
    f"x-statement-count: {len(ops)}",
    "tags:",
    "  - name: dql",
    f"    description: {q('Reads rows. FROM and JOIN are the inputs; the SELECT list is the output schema.')}",
    "  - name: dml",
    f"    description: {q('Mutates rows in a table that relational.yaml already describes.')}",
    "  - name: ddl",
    f"    description: {q('Mutates the schema itself. No resource to address, so every one is post.')}",
    "  - name: pragma",
    f"    description: {q('Reads or sets engine state rather than a table.')}",
    "paths:",
]

# DDL mutates the schema and has no resource to address, so it is tagged and
# kept on `post`; only an idempotent INSERT earns `put`.
CLASS = {"SELECT": "dql", "WITH": "dql", "PRAGMA": "pragma", "INSERT": "dml", "REPLACE": "dml",
         "UPDATE": "dml", "DELETE": "dml", "CREATE": "ddl", "DROP": "ddl", "ALTER": "ddl"}
METHOD = {"dql": "get", "pragma": "get", "ddl": "post"}


def method_of(verb, sql):
    cls = CLASS.get(verb, "ddl")
    if cls != "dml":
        return METHOD[cls], cls
    if verb == "DELETE":
        return "delete", cls
    if verb == "UPDATE":
        return "patch", cls
    idempotent = re.search(r"\bINSERT\s+OR\s+(IGNORE|REPLACE)\b", sql, re.I) or verb == "REPLACE"
    return ("put" if idempotent else "post"), cls

for o in ops:
    L.append(f"  {q(o['url'])}:")
    method, cls = method_of(o["verb"], o["sql"])
    L.append(f"    {method}:")
    L.append(f"      operationId: {o['verb'].lower()}_{(o['writes'] or o['reads'] or ['_'])[0]}_{o['key']}")
    L.append(f"      summary: {q(o['sql'][:110])}")
    L.append(f"      x-sql: {q(o['sql'])}")
    L.append(f"      x-source: {q(o['src'])}")
    L.append(f"      x-verb: {o['verb']}")
    L.append(f"      x-sql-class: {cls}")
    L.append(f"      x-idempotent: {'true' if method in ('get', 'put', 'delete') else 'false'}")
    L.append(f"      tags: [{cls}]")
    L.append(f"      x-reads: [{', '.join(o['reads'])}]")
    L.append(f"      x-writes: [{', '.join(o['writes'])}]")
    if not o["binds"]:
        L.append("      parameters: []")
    else:
        L.append("      parameters:")
        used = Counter()
        for i in range(o["binds"]):
            col = o["where"][i] if i < len(o["where"]) else None
            pname = col or f"p{i + 1}"
            used[pname] += 1
            if used[pname] > 1:
                pname = f"{pname}#{used[pname]}"
            L.append(f"        - name: {q(pname)}")
            L.append("          in: query")
            L.append("          required: true")
            L.append(f"          x-bind-index: {i + 1}")
            if col:
                L.append(f"          x-column: {q(col)}")
            L.append(f"          schema: {{ type: {col_type(col or '', o['reads']) if col else 'string'} }}")
    L.append("      responses:")
    if o["cols"]:
        L.append('        "200":')
        L.append("          description: rows")
        L.append("          content:")
        L.append("            application/json:")
        L.append("              schema:")
        L.append("                type: array")
        L.append("                items:")
        L.append("                  type: object")
        L.append(f"                  required: [{', '.join(q(c) for c in o['cols'])}]")
        L.append("                  properties:")
        for c in o["cols"]:
            L.append(f"                    {q(c)}: {{ type: [{col_type(c, o['reads'])}, \"null\"] }}")
    else:
        L.append('        "200": { description: rows affected }')
    L.append('        "400": { description: sqlite error }')

OUT.write_text("\n".join(L) + "\n")
sel = sum(1 for o in ops if o["cols"])
print(f"{len(ops)} statements ({sel} with typed output columns), skipped {sum(skipped.values())} -> {OUT}")
for k, v in skipped.most_common(5):
    print(f"  skipped {v}: {k}")
