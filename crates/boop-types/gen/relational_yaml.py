#!/usr/bin/env python3
"""Reverse-describe the boop store into relational.yaml.

Reads a live store because the DDL lives in migration code, not in a schema
file; `dict_*` interning is recovered by matching the `<col>_id` convention.
"""
import re
import sqlite3
import sys
from pathlib import Path

DB = sys.argv[1] if len(sys.argv) > 1 else str(Path.home() / ".agent/boop.db")
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).parent.parent / "relational.yaml"

TYPES = {"INTEGER": "integer", "TEXT": "string", "REAL": "number", "BLOB": "string", "": "string"}
TS = re.compile(r"(_ts|_at|_ms)$")

con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
tables = [r[0] for r in con.execute(
    "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY 1")]
dicts = {t for t in tables if t.startswith("dict_")}

cols, pk = {}, {}
for t in tables:
    info = list(con.execute(f'PRAGMA table_info("{t}")'))
    cols[t] = info
    pk[t] = [c[1] for c in info if c[5]]

refs = {}
for t in tables:
    for c in cols[t]:
        name = c[1]
        if not name.endswith("_id"):
            continue
        cand = "dict_" + name[:-3]
        if cand in dicts:
            refs.setdefault(t, {})[name] = cand

back = {}
for t, m in refs.items():
    for col, d in m.items():
        back.setdefault(d, set()).add(t)


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = [
    "# generated by crates/boop-types/gen/relational_yaml.py from a live store",
    "openapi: 3.1.0",
    "info:",
    "  title: boop store",
    f'  version: "{con.execute("PRAGMA user_version").fetchone()[0]}"',
    "  license:",
    '    name: "MIT OR Apache-2.0"',
    '    identifier: "MIT OR Apache-2.0"',
    "servers:",
    '  - url: "~/.agent/boop.db"',
    "    description: the sqlite store this schema was read from",
    f"x-table-count: {len(tables)}",
    f"x-dict-count: {len(dicts)}",
    "components:",
    "  schemas:",
]

for t in tables:
    req = [c[1] for c in cols[t] if c[3] or c[5]]
    lines.append(f"    {t}:")
    lines.append(f"      x-boop-table: {t}")
    if t in dicts:
        users = sorted(back.get(t, ()))
        lines.append("      x-boop-kind: dict")
        lines.append(f"      x-boop-interned-by: [{', '.join(users)}]")
    if pk[t]:
        lines.append(f"      x-boop-primary-key: [{', '.join(pk[t])}]")
    lines.append("      type: object")
    lines.append(f"      required: [{', '.join(req)}]" if req else "      required: []")
    lines.append("      properties:")
    for c in cols[t]:
        name, decl, notnull = c[1], (c[2] or "").upper().split("(")[0], c[3]
        base = TYPES.get(decl, "string")
        prop = [f'type: [{base}, "null"]' if not notnull else f"type: {base}"]
        if TS.search(name):
            prop.append("format: epoch-ms")
        d = refs.get(t, {}).get(name)
        if d:
            prop.append(f"x-dict: {d}")
            # An interned reference that is not an integer cannot join its dict.
            if base != "integer":
                prop.append(f'x-boop-defect: "x-dict on a {base} column; joins {d}.id as 0 rows"')
        lines.append(f"        {name}: {{ {', '.join(prop)} }}")

OUT.write_text("\n".join(lines) + "\n")
print(f"{len(tables)} tables ({len(dicts)} dict), {sum(len(v) for v in cols.values())} columns -> {OUT}")
