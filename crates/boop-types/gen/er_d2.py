#!/usr/bin/env python3
"""Cluster the store into CRUD families and draw the ER board.

A table's family is the first anchor column it carries, in ANCHORS order, so a
table joins exactly one family and the order encodes which spine wins a tie.
"""
import re
import sqlite3
import sys
from collections import Counter, defaultdict
from pathlib import Path

DB = sys.argv[1] if len(sys.argv) > 1 else str(Path.home() / ".agent/boop.db")
BASE = Path(__file__).parent.parent
QY = (BASE / "queries.yaml").read_text()

ANCHORS = [
    ("trace", ("trace_id",)),
    ("lane", ("lane", "lane_id")),
    ("mail", ("message_id", "mailbox", "reply_to")),
    ("session", ("session_id", "root_session_id")),
    ("route", ("route", "route_id")),
    ("favorite", ("favorite_id",)),
    ("tag", ("tag_id", "tag")),
    ("turn", ("turn", "comment_id")),
]
FILL = {"trace": "#7a3d8f", "lane": "#a8531c", "mail": "#8f2f3f", "session": "#1d6b4f",
        "route": "#1f4f82", "favorite": "#5b5f22", "tag": "#146b74", "turn": "#2f3f8f",
        "shared": "#3a3f4a", "orphan": "#6b2020", "other": "#4a4a4a"}
FG = {k: "#f2f5f8" for k in FILL}

con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
tables = [r[0] for r in con.execute(
    "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY 1")]
cols = {t: [c[1] for c in con.execute(f'PRAGMA table_info("{t}")')] for t in tables}
rows = {t: con.execute(f'SELECT COUNT(*) FROM "{t}"').fetchone()[0] for t in tables}
dicts = {t for t in tables if t.startswith("dict_")}

crud = defaultdict(set)
for url, meth, body in re.findall(r'^  "(/[^"]+)":\n    (\w+):\n(.*?)(?=^  "|\Z)', QY, re.S | re.M):
    verb = re.search(r"x-verb: (\w+)", body).group(1)
    for t in [x.strip() for x in re.search(r"x-reads: \[(.*?)\]", body).group(1).split(",") if x.strip()]:
        crud[t].add("R")
    for t in [x.strip() for x in re.search(r"x-writes: \[(.*?)\]", body).group(1).split(",") if x.strip()]:
        crud[t].add({"INSERT": "C", "REPLACE": "C", "UPDATE": "U", "DELETE": "D"}.get(verb, "R"))


def anchor_family(t):
    for name, keys in ANCHORS:
        if any(k in cols[t] for k in keys):
            return name
    return "other"


# A dict table is a vocabulary, not a domain. It belongs to the family that
# references it, and only a dict two or more families share is its own thing.
fam = {t: anchor_family(t) for t in tables if t not in dicts}


def references(stem, col):
    """Three spellings are live in this schema: <stem>_id, <stem>_ref, and a
    prefixed <x>_<stem>_id. sync_cursor.record_id_id doubles the suffix."""
    return col in (f"{stem}_id", f"{stem}_ref", f"{stem}_id_id") or col.endswith(f"_{stem}_id")


dict_users = {}
for d in dicts:
    stem = d[5:]
    dict_users[d] = [(t, c) for t in tables if t not in dicts for c in cols[t] if references(stem, c)]
    owners = {fam[t] for t, _ in dict_users[d]}
    fam[d] = owners.pop() if len(owners) == 1 else ("shared" if owners else "orphan")
members = defaultdict(list)
for t in tables:
    members[fam[t]].append(t)

refs = defaultdict(set)
for t in tables:
    for d, us in dict_users.items():
        if any(u == t for u, _ in us):
            refs[t].add(d)

fam_edge = Counter()
for t, ds in refs.items():
    for d in ds:
        fam_edge[(fam[t], d)] += 1


def q(s):
    return '"' + str(s).replace('"', '\\"') + '"'


order = [k for k, _ in ANCHORS] + ["other", "shared", "orphan"]
L = [
    "# generated by crates/boop-types/gen/er_d2.py",
    "vars: { d2-config: { layout-engine: elk; theme-id: 200; pad: 30 } }",
    "direction: down",
    "classes: {",
]
for k in FILL:
    L.append(f"  f_{k}: {{ style: {{ fill: {q(FILL[k])}; stroke: \"#0b0d10\"; font-color: {q(FG[k])}; border-radius: 6 }} }}")
L.append("}")

for f in order:
    if not members.get(f):
        continue
    ops = "".join(sorted(set().union(*(crud[t] for t in members[f])) or {"-"}))
    L.append(f"{f}: {q(f'{f}  [{ops}]  {len(members[f])} tables')} {{ class: f_{f} }}")

top = sorted(dicts, key=lambda d: -sum(1 for t in tables if d in refs[t]))[:6]
L.append(f"dicts: {q(f'interned vocabularies  {len(dicts)} tables')} {{")
L.append("  class: f_shared")
for d in top:
    L.append(f"  {d}: {q(d + '  ' + str(rows[d]) + ' rows')} {{ class: f_shared }}")
L.append("}")

for (f, d), n in fam_edge.most_common():
    if d not in top:
        continue
    L.append(f"{f} -> dicts.{d}: {q(str(n))} {{ style: {{ stroke: {q(FILL[f])}; opacity: 0.8 }} }}")

(BASE / "er.d2").write_text("\n".join(L) + "\n")

C = ["# generated by crates/boop-types/gen/er_d2.py", f"x-family-count: {len([f for f in order if members.get(f)])}", "families:"]
for f in order:
    if not members.get(f):
        continue
    C.append(f"  {f}:")
    C.append(f"    table_count: {len(members[f])}")
    C.append(f"    row_total: {sum(rows[t] for t in members[f])}")
    C.append("    tables:")
    for t in sorted(members[f], key=lambda x: -rows[x]):
        ops = "".join(sorted(crud[t])) or "-"
        C.append(f"      {t}: {{ crud: {q(ops)}, rows: {rows[t]}, columns: {len(cols[t])} }}")
(BASE / "clusters.yaml").write_text("\n".join(C) + "\n")

print(f"{len(tables)} tables -> {len([f for f in order if members.get(f)])} families; er.d2 + clusters.yaml")
for f in order:
    if members.get(f):
        print(f"  {f:<9} {len(members[f]):>3} tables  {sum(rows[t] for t in members[f]):>9} rows")
