#!/usr/bin/env python3
"""Emit env.yaml, sql.yaml and crates.yaml from extract call facts.

The literal an effect acts on (an env var name, a SQL statement) is not in the
call record, so each site is resolved by reading the source that follows its
callee span.
"""
import json
import re
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
OUT = Path(__file__).parent.parent
CRATES = ["boop", "boop-acp", "boop-harness", "boop-mux", "boop-proc", "boop-store", "boop-turnstrip", "boop-turnvis"]

files = sorted(p for c in CRATES for p in (ROOT / "crates" / c / "src").rglob("*.rs"))
print(f"{len(files)} files", file=sys.stderr)

ENVFN = {"var", "var_os", "set_var", "remove_var", "vars", "vars_os"}
SQLFN = {"execute", "execute_batch", "prepare", "prepare_cached", "query_row", "query_map", "query_and_then"}
OSFN = {
    "new": "process.spawn", "spawn": "process.spawn", "output": "process.spawn", "status": "process.spawn",
    "write": "fs.write", "create": "fs.write", "create_dir_all": "fs.write", "remove_file": "fs.write",
    "remove_dir_all": "fs.write", "rename": "fs.write", "copy": "fs.write", "set_permissions": "fs.write",
    "read": "fs.read", "read_to_string": "fs.read", "read_dir": "fs.read", "metadata": "fs.read",
    "canonicalize": "fs.read", "exit": "process.exit", "set_current_dir": "process.cwd",
    "current_dir": "process.cwd", "connect": "net", "bind": "net",
}

envs = defaultdict(lambda: {"ops": set(), "files": set()})
sqls = defaultdict(lambda: {"tables": Counter(), "files": set(), "sites": 0})
oss = defaultdict(lambda: {"calls": Counter(), "files": set()})

VERB = re.compile(r"\b(SELECT|INSERT|UPDATE|DELETE|CREATE TABLE|CREATE INDEX|CREATE VIEW|DROP|ALTER|PRAGMA|REPLACE|WITH)\b", re.I)
TBL = re.compile(r"\b(?:FROM|INTO|UPDATE|JOIN|TABLE(?:\s+IF\s+NOT\s+EXISTS)?)\s+([a-z_][a-z0-9_]*)", re.I)
NAME = re.compile(r'"([A-Z][A-Z0-9_]{2,})"')

for f in files:
    out = subprocess.run(["extract", "--family", "call", str(f)], capture_output=True, text=True).stdout
    src = f.read_bytes()
    rel = str(f.relative_to(ROOT))
    crate = rel.split("/")[1]
    for line in out.splitlines():
        d = json.loads(line)
        if d.get("record") != "site":
            continue
        callee, path = d.get("callee") or "", d.get("callee_path") or ""
        end = d["span"]["end"]
        if callee in ENVFN and "env::" in path:
            m = NAME.search(src[end:end + 160].decode("utf8", "replace"))
            if m:
                e = envs[m.group(1)]
                e["ops"].add(callee)
                e["files"].add(rel)
        if callee in SQLFN:
            tail = src[end:end + 1500].decode("utf8", "replace")
            v = VERB.search(tail[:600])
            if v:
                s = sqls[v.group(1).upper()]
                s["sites"] += 1
                s["files"].add(rel)
                for t in TBL.findall(tail):
                    s["tables"][t.lower()] += 1
        group = OSFN.get(callee)
        if group and any(k in path for k in ("std::process", "std::fs", "Command", "std::net", "tokio::")):
            o = oss[group]
            o["calls"][f"{path}::{callee}" if path else callee] += 1
            o["files"].add(rel)


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


env_lines = ["# generated by crates/boop-types/gen/boundaries_yaml.py", f"x-name-count: {len(envs)}", "env:"]
for name in sorted(envs):
    e = envs[name]
    env_lines.append(f"  {name}:")
    env_lines.append(f"    ops: [{', '.join(sorted(e['ops']))}]")
    env_lines.append(f"    file_count: {len(e['files'])}")
    env_lines.append(f"    files: [{', '.join(q(x) for x in sorted(e['files']))}]")
(OUT / "env.yaml").write_text("\n".join(env_lines) + "\n")

sql_lines = ["# generated by crates/boop-types/gen/boundaries_yaml.py",
             f"x-site-count: {sum(v['sites'] for v in sqls.values())}", "statements:"]
for verb in sorted(sqls, key=lambda k: -sqls[k]["sites"]):
    s = sqls[verb]
    sql_lines.append(f"  {q(verb)}:")
    sql_lines.append(f"    sites: {s['sites']}")
    sql_lines.append(f"    file_count: {len(s['files'])}")
    sql_lines.append("    tables:")
    for t, n in s["tables"].most_common():
        sql_lines.append(f"      {t}: {n}")
(OUT / "sql.yaml").write_text("\n".join(sql_lines) + "\n")

deps = {}
for c in CRATES:
    toml = (ROOT / "crates" / c / "Cargo.toml").read_text()
    deps[c] = sorted({m for m in re.findall(r"^\s*(boop[\w-]*)\s*=", toml, re.M) if m != c})

crate_lines = ["# generated by crates/boop-types/gen/boundaries_yaml.py", f"x-crate-count: {len(CRATES)}", "crates:"]
for c in CRATES:
    srcs = [f for f in files if f"/crates/{c}/" in str(f)]
    owns = sorted({g for g, o in oss.items() if any(f"/{c}/" in x or x.startswith(f"crates/{c}/") for x in o["files"])})
    crate_lines.append(f"  {c}:")
    crate_lines.append(f"    files: {len(srcs)}")
    crate_lines.append(f"    depends_on: [{', '.join(deps[c])}]")
    crate_lines.append(f"    effects: [{', '.join(owns)}]")
crate_lines.append("effect_totals:")
for g in sorted(oss):
    crate_lines.append(f"  {g}: {sum(oss[g]['calls'].values())}")
(OUT / "crates.yaml").write_text("\n".join(crate_lines) + "\n")

print(f"env {len(envs)} names | sql {sum(v['sites'] for v in sqls.values())} sites | crates {len(CRATES)}")
